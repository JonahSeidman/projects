#!/usr/bin/env node
/**
 * Makes web-sized copies of everything in images/ and writes media-manifest.js.
 * Run locally (macOS) after adding or changing images or videos:
 *   node optimize-media.js        (or: npm run optimize)
 * Needs cwebp and ffmpeg on PATH (brew install webp ffmpeg); sips ships with macOS.
 *
 *   images/foo.png  ->  images/web/foo-960.webp, foo-1600.webp, foo-2400.webp
 *                       (only widths smaller than the original; the original
 *                        width is used when it is under 2400)
 *   images/foo.mp4  ->  images/web/foo.mp4 (H.264, longest side <= 1280,
 *                        no audio, faststart), used only if it is smaller
 *
 * The originals stay in images/ untouched. script.js reads window.MEDIA to
 * pick srcset, reserve layout space and choose the lightbox size; anything
 * missing from the manifest falls back to the original file.
 */
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = __dirname;
const SRC_DIR = path.join(ROOT, "images");
const OUT_DIR = path.join(SRC_DIR, "web");
const MANIFEST = path.join(ROOT, "media-manifest.js");

const IMAGE_EXTS = new Set([".jpg", ".jpeg", ".png"]);
const WIDTHS = [960, 1600, 2400];
const GRID_MAX = 1600; // widths above this are lightbox-only
const VIDEO_MAX = 1280;

fs.mkdirSync(OUT_DIR, { recursive: true });

const rel = (p) => path.relative(ROOT, p).split(path.sep).join("/");
const fresh = (out, src) =>
  fs.existsSync(out) && fs.statSync(out).mtimeMs >= fs.statSync(src).mtimeMs;

function dims(file) {
  const out = execFileSync("sips", ["-g", "pixelWidth", "-g", "pixelHeight", file], { encoding: "utf8" });
  return {
    w: Number(/pixelWidth: (\d+)/.exec(out)[1]),
    h: Number(/pixelHeight: (\d+)/.exec(out)[1]),
  };
}

function widthsFor(w0) {
  const ws = WIDTHS.filter((w) => w < w0);
  if (w0 <= WIDTHS[WIDTHS.length - 1]) {
    // keep the full-resolution copy, dropping a step that is nearly the same size
    if (ws.length && w0 - ws[ws.length - 1] < 240) ws.pop();
    ws.push(w0);
  }
  return ws;
}

const manifest = {};
const keep = new Set();
let made = 0;

const files = fs
  .readdirSync(SRC_DIR)
  .filter((f) => fs.statSync(path.join(SRC_DIR, f)).isFile())
  .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

for (const file of files) {
  const src = path.join(SRC_DIR, file);
  const ext = path.extname(file).toLowerCase();
  const base = file.slice(0, -ext.length);

  if (IMAGE_EXTS.has(ext)) {
    const { w, h } = dims(src);
    const variants = [];
    for (const vw of widthsFor(w)) {
      const out = path.join(OUT_DIR, `${base}-${vw}.webp`);
      keep.add(out);
      if (!fresh(out, src)) {
        const args = ["-quiet", "-q", "82", "-m", "5", "-mt", "-sharp_yuv", "-metadata", "none"];
        if (vw < w) args.push("-resize", String(vw), "0");
        execFileSync("cwebp", [...args, src, "-o", out]);
        made++;
      }
      variants.push([rel(out), vw]);
    }
    const grid = variants.filter(([, vw]) => vw <= GRID_MAX);
    const big = variants[variants.length - 1];
    manifest["images/" + file] = {
      w,
      h,
      v: grid.length ? grid : [variants[0]],
      ...(big[1] > GRID_MAX ? { xl: big[0] } : {}),
    };
  } else if (ext === ".mp4") {
    const out = path.join(OUT_DIR, file);
    keep.add(out);
    if (!fresh(out, src)) {
      const scale = `scale='if(gte(iw,ih),min(${VIDEO_MAX},iw),-2)':'if(gte(iw,ih),-2,min(${VIDEO_MAX},ih))'`;
      execFileSync("ffmpeg", [
        "-v", "error", "-y", "-i", src, "-vf", scale,
        "-c:v", "libx264", "-preset", "slow", "-crf", "27", "-profile:v", "high",
        "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-an", out,
      ]);
      made++;
    }
    if (fs.statSync(out).size < fs.statSync(src).size) manifest["images/" + file] = { src: rel(out) };
  }
}

// drop outputs whose source is gone
for (const f of fs.readdirSync(OUT_DIR)) {
  const p = path.join(OUT_DIR, f);
  if (!keep.has(p)) fs.unlinkSync(p);
}

fs.writeFileSync(
  MANIFEST,
  "/* AUTO-GENERATED by optimize-media.js. Run `node optimize-media.js` after changing images/. */\n" +
    "window.MEDIA = " + JSON.stringify(manifest, null, 1) + ";\n"
);

const size = (dir) => fs.readdirSync(dir).reduce((s, f) => {
  const p = path.join(dir, f);
  return fs.statSync(p).isFile() ? s + fs.statSync(p).size : s;
}, 0);
console.log(
  `encoded ${made} file(s); ${Object.keys(manifest).length} manifest entries; ` +
    `images/ ${(size(SRC_DIR) / 1e6).toFixed(1)} MB -> images/web/ ${(size(OUT_DIR) / 1e6).toFixed(1)} MB`
);
